import asyncio
import os
import streamlit as st
from dotenv import load_dotenv

from autogen_agentchat.agents import AssistantAgent
from autogen_ext.models.openai import OpenAIChatCompletionClient

# Load environment variables
load_dotenv()

st.set_page_config(page_title="AutoGen HR Assistant", page_icon="🤖", layout="centered")

st.title("🤖 AutoGen HR Assistant")
st.write("Generate custom job descriptions dynamically using your AI HR agent.")

# Sidebar inputs for user customization
st.sidebar.header("Job Parameters")
role = st.sidebar.text_input("Job Role", value="Junior Python Developer")
experience_level = st.sidebar.selectbox("Experience Level", ["Junior", "Mid-Level", "Senior", "Lead"])
num_lines = st.sidebar.slider("Number of Bullet Points / Lines", min_value=3, max_value=10, value=5)

# Async function to run the agent and collect the response
async def generate_job_description(target_role, level, lines):
    # Initialize model client
    model_client = OpenAIChatCompletionClient(model="gpt-4o-mini")

    # Create the AssistantAgent
    assistant = AssistantAgent(
        name="hr_assistant",
        system_message="You are a professional HR assistant.",
        model_client=model_client,
    )

    # Formulate the task dynamically based on sidebar inputs
    task = f"Write a {lines}-line job description for a {level} {target_role}, formatted as {lines} distinct bullet points."

    # Run the agent stream and gather outputs
    response_text = ""
    async for message in assistant.run_stream(task=task):
        # We capture the text messages generated by the assistant
        if hasattr(message, "source") and message.source == "hr_assistant":
            if hasattr(message, "content"):
                response_text = message.content

    # Close the model client to prevent hanging
    await model_client.close()
    return response_text

# Button to trigger generation
if st.button("Generate Job Description", type="primary"):
    if not os.getenv("OPENAI_API_KEY"):
        st.error("⚠️ OPENAI_API_KEY is missing! Please check your .env file.")
    else:
        with st.spinner(f"Generating {num_lines}-line description for a {experience_level} {role}..."):
            # Run the async function using asyncio
            try:
                result = asyncio.run(generate_job_description(role, experience_level, num_lines))
                st.success("Job description generated successfully!")
                st.markdown("### 📄 Output:")
                st.markdown(result)
            except Exception as e:
                st.error(f"An error occurred: {e}")